def render_dynamic_form_fields(fields):
    """
    Renders dynamic form fields with expanded input controls (email, date, tel, file upload)
    and standardized pattern-matching IDs for pre-payment validation.
    """
    components = []

    for f in fields:
        field_id = f["id"]
        label_text = f["label"]
        is_required = f.get("required", False)
        field_type = f.get("type", "text")

        # Required field visual indicator (*)
        label_children = [
            label_text,
            html.Span(" *" if is_required else "", style={"color": "red", "fontWeight": "bold"})
        ]

        field_children = [
            html.Label(label_children, className="form-label fw-bold mt-2")
        ]

        if f.get("description"):
            field_children.append(html.P(f["description"], className="small text-muted mb-1"))

        # Derive placeholder text
        clean_label = label_text.split("(")[0].replace("*", "").strip()
        placeholder_text = f.get("placeholder", f"Enter {clean_label}...")

        # 1. Contact Email Input
        if field_type == "email":
            field_children.append(
                dbc.Input(
                    id={"type": "form-input", "id": field_id},
                    type="email",
                    placeholder="name@example.com",
                    className="form-control w-100"
                )
            )

        # 2. Date of Birth Input
        elif field_type == "date":
            field_children.append(
                dbc.Input(
                    id={"type": "form-input", "id": field_id},
                    type="date",
                    className="form-control w-100"
                )
            )

        # 3. Phone Number Input
        elif field_type == "tel":
            field_children.append(
                dbc.Input(
                    id={"type": "form-input", "id": field_id},
                    type="tel",
                    placeholder="(304) 555-0123",
                    className="form-control w-100"
                )
            )

        # 4. Headshot Photo Upload Component
        elif field_type == "file":
            field_children.append(
                html.Div([
                    dcc.Upload(
                        id={"type": "form-upload", "id": field_id},
                        children=html.Div([
                            "Drag & Drop or ",
                            html.A("Select Headshot Photo", style={"color": "var(--mt-primary)", "fontWeight": "bold"})
                        ]),
                        style={
                            "width": "100%",
                            "height": "64px",
                            "lineHeight": "64px",
                            "borderWidth": "2px",
                            "borderStyle": "dashed",
                            "borderRadius": "8px",
                            "textAlign": "center",
                            "backgroundColor": "#f8f9fa",
                            "cursor": "pointer"
                        },
                        multiple=False
                    ),
                    html.Div(id={"type": "upload-status", "id": field_id}, className="mt-2 text-muted small")
                ])
            )

        # 5. Multiline Text Area
        elif field_type == "textarea":
            field_children.append(
                dcc.Textarea(
                    id={"type": "form-input", "id": field_id},
                    className="form-control w-100",
                    rows=3,
                    placeholder=placeholder_text
                )
            )

        # 6. Dropdown Options
        elif field_type == "dropdown":
            field_children.append(
                dcc.Dropdown(
                    id={"type": "form-input", "id": field_id},
                    options=[{"label": opt, "value": opt} for opt in f.get("options", [])],
                    clearable=not is_required,
                    className="w-100 mb-2",
                    placeholder=f"Select {clean_label}..."
                )
            )

        # 7. Radio Buttons
        elif field_type == "radio":
            field_children.append(
                dbc.RadioItems(
                    id={"type": "form-input", "id": field_id},
                    options=[{"label": opt, "value": opt} for opt in f.get("options", [])],
                    className="custom-radio-group mb-2"
                )
            )

        # 8. Standard Text Input Fallback
        else:
            field_children.append(
                dcc.Input(
                    id={"type": "form-input", "id": field_id},
                    type="text",
                    className="form-control w-100",
                    placeholder=placeholder_text
                )
            )

        components.append(html.Div(className="mb-3", children=field_children))

    return components

def render_addons_section(addons):
    """Renders optional categories (Themewear, Talent, Photogenic, etc.)"""
    if not addons:
        return None

    addon_cards = []
    for addon in addons:
        options_list = [
            {"label": f" {opt['label']}", "value": opt['label']}
            for opt in addon.get("options", [])
        ]

        default_val = addon["options"][0]["label"] if addon.get("options") else None
        for opt in addon.get("options", []):
            if opt["label"].lower() in ["no", "none", "no thanks", "i do not wish to enter"]:
                default_val = opt["label"]
                break

        addon_cards.append(
            html.Div(className="mb-4 pb-3 border-bottom", children=[
                html.H6(addon.get("title", "").split("\n")[0], className="fw-bold text-dark mb-1"),
                html.P(addon.get("description"), className="small text-muted mb-2", style={"whiteSpace": "pre-line"}),
                dcc.RadioItems(
                    id={'type': 'addon-select', 'index': addon.get("id", sanitize_id(addon.get("title", "")))},
                    options=options_list,
                    value=default_val,
                    className="custom-radio-group"
                )
            ])
        )

    return html.Div(className="card card-custom mb-4", children=[
        html.Div(className="card-header card-header-secondary", children=[
            html.H5("Optional Categories & Add-Ons", className="mb-0 fs-5")
        ]),
        html.Div(className="card-body", children=addon_cards)
    ])

def render_disclaimer(disclaimer_data):
    """Renders rules & disclaimer agreement card"""
    if not disclaimer_data:
        return html.Div(dcc.RadioItems(id="disclaimer-agreement", style={"display": "none"}), style={"display": "none"})

    raw_title = disclaimer_data.get("title", "")
    text = disclaimer_data.get("text", "")

    if not raw_title or len(raw_title) > 80 or "\n" in raw_title or raw_title == text:
        header_title = "Pageant Rules & Sportsmanship Disclaimer"
    else:
        header_title = raw_title

    return html.Div(className="card card-custom disclaimer-card mb-4", children=[
        html.Div(className="card-header card-header-disclaimer p-3", children=[
            html.H5(header_title, className="mb-0 fs-5")
        ]),
        html.Div(className="card-body", children=[
            html.Div(
                text,
                className="disclaimer-full-text mb-3",
                style={"whiteSpace": "pre-line"}
            ),
            dcc.RadioItems(
                id="disclaimer-agreement",
                options=[{"label": f" {opt}", "value": opt} for opt in disclaimer_data.get("options", [])],
                className="custom-radio-group"
            )
        ])
    ])

def sanitize_id(title):
    import re
    clean = re.sub(r'[^a-zA-Z0-9\s]', '', title).strip().lower()
    return re.sub(r'\s+', '_', clean)

