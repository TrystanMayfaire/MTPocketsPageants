def get_authorized_http(creds):
    """Configures httplib2 to route through PythonAnywhere proxy if environment variables are present."""
    proxy_url = (
        os.environ.get("http_proxy")
        or os.environ.get("https_proxy")
        or os.environ.get("HTTP_PROXY")
        or os.environ.get("HTTPS_PROXY")
    )

    if proxy_url:
        proxy_info = httplib2.proxy_info_from_url(proxy_url)
        http_client = httplib2.Http(proxy_info=proxy_info)
    else:
        http_client = httplib2.Http()

    return google_auth_httplib2.AuthorizedHttp(creds, http=http_client)

def get_google_services():
    service_account_file = os.environ.get("GOOGLE_APPLICATION_CREDENTIALS")
    if not service_account_file or not os.path.exists(service_account_file):
        print("ERROR: Service account credentials file missing.")
        return None, None
    creds = service_account.Credentials.from_service_account_file(service_account_file, scopes=GOOGLE_SCOPES)
    authorized_http = get_authorized_http(creds)
    drive_service = build("drive", "v3", http=authorized_http)
    sheets_service = build("sheets", "v4", http=authorized_http)
    return drive_service, sheets_service

def upload_headshot_to_drive(drive_service, folder_id, base64_contents, contestant_name):
    """Decodes base64 upload and uploads image to Google Drive folder."""
    try:
        header, content = base64_contents.split(",")
        file_bytes = base64.b64decode(content)

        filename = f"{sanitize_id(contestant_name)}_headshot.jpg"
        media = MediaIoBaseUpload(io.BytesIO(file_bytes), mimetype="image/jpeg", resumable=True)

        file_metadata = {
            "name": filename,
            "parents": [folder_id]
        }

        uploaded_file = drive_service.files().create(
            body=file_metadata,
            media_body=media,
            fields="id, webViewLink",
            supportsAllDrives=True
        ).execute()

        # Set permissions so anyone with link can view image in Google Sheet
        drive_service.permissions().create(
            fileId=uploaded_file["id"],
            body={"role": "reader", "type": "anyone"},
            supportsAllDrives=True
        ).execute()

        return uploaded_file.get("webViewLink", "")
    except Exception as e:
        print(f"Error uploading headshot to Drive: {e}")
        return "Upload Failed"

def save_registration_to_sheet(transaction_details, form_input_data, upload_data, selected_division, selected_addons, disclaimer_val):
    """Formats submission payload and appends a row to the Google Sheet."""
    drive_service, sheets_service = get_google_services()
    if not drive_service or not sheets_service:
        return False

    spreadsheet_id = EVENT_CONFIG.get("spreadsheet_id")
    headshot_folder_id = EVENT_CONFIG.get("headshot_folder_id")
    headers = EVENT_CONFIG.get("sheet_headers", [])

    if not spreadsheet_id:
        print("ERROR: spreadsheet_id missing in config.json")
        return False

    # Extract Contestant Name for file naming
    contestant_name = "Contestant"
    for fid, val in form_input_data.items():
        if "name" in fid.lower() and val:
            contestant_name = str(val)
            break

    # Upload Headshot to Drive
    headshot_url = ""
    for fid, contents in upload_data.items():
        if fid == "headshot_upload" and contents:
            headshot_url = upload_headshot_to_drive(drive_service, headshot_folder_id, contents, contestant_name)

    # Build row mapping based on headers
    row_map = {
        "Timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "Transaction ID": transaction_details.get("orderID", "N/A"),
        "Amount Paid": f"${transaction_details.get('amount', '0.00')}",
        "Division": selected_division or "",
        "Disclaimer Agreed": "Yes" if disclaimer_val else "No",
        "Headshot Image Link": headshot_url
    }

    # Add dynamic form fields
    for field in EVENT_CONFIG.get("form_fields", []):
        fid = field["id"]
        if fid != "headshot_upload":
            row_map[field["label"]] = form_input_data.get(fid, "")

    # Add dynamic add-ons
    addons_config = EVENT_CONFIG.get("addons", [])
    if selected_addons and len(selected_addons) == len(addons_config):
        for addon_group, selected_val in zip(addons_config, selected_addons):
            row_map[f"Add-On: {addon_group['title']}"] = selected_val or ""

    # Assemble row matching exact column order in Google Sheet
    row_values = [row_map.get(col, "") for col in headers]

    try:
        sheets_service.spreadsheets().values().append(
            spreadsheetId=spreadsheet_id,
            range="A1",
            valueInputOption="USER_ENTERED",
            insertDataOption="INSERT_ROWS",
            body={"values": [row_values]}
        ).execute()
        print("Successfully saved registration to Google Sheet!")
        return True
    except Exception as e:
        print(f"Error appending row to Google Sheet: {e}")
        return False

