@app.callback(
    Output("payment-validation-store", "data"),
    Output("payment-notice-display", "children"),
    Input({"type": "form-input", "id": ALL}, "value"),
    Input({"type": "form-upload", "id": ALL}, "contents"),
    Input("division-select", "value"),
    Input("disclaimer-agreement", "value"),
    Input("fee-total-display", "children"),
    State({"type": "form-input", "id": ALL}, "id"),
    State({"type": "form-upload", "id": ALL}, "id")
)
def validate_form_and_payment(input_values, upload_contents, selected_division, disclaimer_val, fee_str, input_ids, upload_ids):
    # 1. Parse total numerical fee
    try:
        amount = float(str(fee_str).replace("$", "").strip())
    except (ValueError, TypeError, AttributeError):
        amount = 0.0

    # 2. Map inputs and upload contents by ID
    input_map = {item["id"]: val for item, val in zip(input_ids, input_values)}
    upload_map = {item["id"]: val for item, val in zip(upload_ids, upload_contents)}

    missing_reasons = []

    # 3. Check mandatory form fields from EVENT_CONFIG
    for field in EVENT_CONFIG.get("form_fields", []):
        if field.get("required"):
            fid = field["id"]
            if field.get("type") == "file":
                if not upload_map.get(fid):
                    missing_reasons.append(f"Upload {field['label']}")
            else:
                val = input_map.get(fid)
                if val is None or str(val).strip() == "":
                    missing_reasons.append(f"Fill out '{field['label']}'")

    # 4. Check Division Selection
    if not selected_division:
        missing_reasons.append("Select a Division")

    # 5. Check Rules & Disclaimer Agreement
    disclaimer_cfg = EVENT_CONFIG.get("disclaimer")
    if disclaimer_cfg:
        disclaimer_agreed = False
        if isinstance(disclaimer_val, list):
            disclaimer_agreed = len(disclaimer_val) > 0
        elif isinstance(disclaimer_val, str):
            disclaimer_agreed = disclaimer_val.strip() != ""
        if not disclaimer_agreed:
            missing_reasons.append("Agree to the Rules & Disclaimer")

    is_valid = len(missing_reasons) == 0

    # 6. Generate dynamic status banner UI
    if is_valid:
        notice = html.Div([
            html.Div("✓ Application Complete", className="badge bg-success mb-2 p-2 w-100 fs-6"),
            html.P("Complete payment below via PayPal or Card to finalize entry.", className="small text-white-50 mb-0")
        ])
    else:
        notice = html.Div(className="p-3 bg-dark bg-opacity-50 border border-warning rounded text-start", children=[
            html.Div("⚠️ Payment Locked", className="fw-bold text-warning small mb-1"),
            html.P("Complete the following to unlock payment:", className="small text-white-50 mb-1"),
            html.Ul(
                [html.Li(r, className="small text-white-50") for r in missing_reasons],
                className="mb-0 ps-3"
            )
        ])

    return {"is_valid": is_valid, "amount": amount}, notice

